"""Inspect every raw dataset: columns, rows, null rates, samples.

Why: column names are read from the files, never assumed. The output feeds
docs/DATA_CARD.md and docs/data_preprocessing_log.md.

Usage: python scripts/data/inspect_raw.py [--out docs/notes/raw_inspection.md]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from scripts.data.common import mask_pii

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw"

# Folder -> files to inspect. The huge pre-encoded BERT sheet in trial_1 is skipped
# (same rows as the labelled file, plus token columns we do not use).
FILES: dict[str, list[str]] = {
    "upwork_jobs_50k": ["upwork-jobs.csv"],
    "all_upwork_jobs_200k": [
        "all_upwork_jobs_2024-02-07-2024-03-24.csv",
        "all_upwork_jobs_2024-03-24-2024-05-21.csv",
        "all_upwork_jobs_2024-05-21-2024-07-25.csv",
    ],
    "upwork_freelance_jobs_60k": ["Final_Upwork_Dataset.csv"],
    "freelance_contracts_1_3m": ["contracts.csv"],
    "freelancer_success_churn": ["freelancer_gig_success_dataset.csv"],
    "trial_1": ["processed_labeled_dataset_without_encoding.xlsx"],
}


def read_any(path: Path) -> pd.DataFrame:
    if path.suffix == ".xlsx":
        return pd.read_excel(path)
    return pd.read_csv(path, low_memory=False, encoding="utf-8-sig")


def describe(name: str, df: pd.DataFrame) -> str:
    lines = [f"## {name}", "", f"Rows: {len(df):,}  Columns: {df.shape[1]}", ""]
    lines += ["| column | dtype | null % | example |", "|---|---|---|---|"]
    for col in df.columns:
        non_null = df[col].dropna()
        example = mask_pii(str(non_null.iloc[0]))[:60].replace("|", "/").replace("\n", " ") if len(non_null) else ""
        lines.append(f"| {col} | {df[col].dtype} | {df[col].isna().mean() * 100:.1f} | {example} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "docs" / "notes" / "raw_inspection.md"))
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    sections = ["# Raw dataset inspection", "", "Generated by scripts/data/inspect_raw.py.", ""]
    for folder, files in FILES.items():
        frames = []
        for f in files:
            path = RAW / folder / f
            if not path.exists():
                print(f"MISSING {path}")
                continue
            frames.append(read_any(path))
        if not frames:
            continue
        df = pd.concat(frames, ignore_index=True)
        text = describe(folder, df)
        print(text)
        sections.append(text)
    Path(args.out).write_text("\n".join(sections), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
